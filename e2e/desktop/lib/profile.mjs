// Builds a throwaway Zotero profile on the host. The same directory is
// mounted into the container as /work, so every path written into prefs is the
// in-container path (CONTAINER_WORK), not the host one.

import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ADDON_SRC = path.join(here, '..', 'addon');
export const ADDON_ID = 'gotero-e2e@gotero.invalid';
export const CONTAINER_WORK = '/work';

function prefLine(name, value) {
  return `user_pref(${JSON.stringify(name)}, ${JSON.stringify(value)});`;
}

/**
 * @param {string} workDir host directory that becomes /work
 * @param {object} o
 * @param {string} o.apiURL      what the client should use as extensions.zotero.api.url
 * @param {string} o.streamURL   websocket URL for the stream server
 * @param {number} o.port        connector server port inside the container
 */
export function createProfile(workDir, { apiURL, streamURL, port, extraPrefs = {} }) {
  const profileDir = path.join(workDir, 'profile');
  const dataDir = `${CONTAINER_WORK}/profile/zotero-data`;
  mkdirSync(path.join(profileDir, 'extensions'), { recursive: true });
  mkdirSync(path.join(profileDir, 'zotero-data'), { recursive: true });

  // An unpacked directory named after the add-on ID is picked up by the
  // profile scan on startup, no XPI needed.
  cpSync(ADDON_SRC, path.join(profileDir, 'extensions', ADDON_ID), { recursive: true });

  const z = (n) => `extensions.zotero.${n}`;
  const prefs = {
    // Where the client talks to. The trailing slash on api.url matters: the
    // client appends paths without adding one.
    [z('api.url')]: apiURL.endsWith('/') ? apiURL : `${apiURL}/`,
    [z('streaming.url')]: streamURL,
    [z('streaming.enabled')]: true,
    // Off by default so tests control when syncs happen; the stream scenario
    // flips it on through the add-on.
    [z('sync.autoSync')]: false,

    // No first-run or update prompts, nothing that opens a window or phones home
    [z('firstRun2')]: false,
    [z('firstRunGuidance')]: false,
    [z('automaticScraperUpdates')]: false,
    [z('reportTranslationFailure')]: false,
    [z('retractions.enabled')]: false,
    [z('dataDir')]: dataDir,
    [z('useDataDir')]: true,
    'app.update.enabled': false,
    'app.update.auto': false,
    'app.update.checkInstallTime': false,
    'app.update.silent': false,
    'browser.shell.checkDefaultBrowser': false,
    'datareporting.policy.dataSubmissionEnabled': false,
    'toolkit.telemetry.enabled': false,

    // The connector server doubles as our remote control channel
    [z('httpServer.enabled')]: true,
    [z('httpServer.port')]: port,

    // Debug output goes to stdout (-ZoteroDebugText) and is redirected to
    // /work/zotero.log by the entrypoint
    [z('debug.log')]: true,
    [z('debug.level')]: 5,
    [z('debug.stackTrace')]: true,

    // Let an unsigned add-on in the profile load without a confirmation
    // prompt: scope 0 disables the "new add-on" auto-disable, 15 enables all
    // scopes, and signature checks are off (Zotero's own builds already
    // don't enforce them, this is belt and braces for older versions).
    'extensions.autoDisableScopes': 0,
    'extensions.enabledScopes': 15,
    'xpinstall.signatures.required': false,
    'extensions.langpacks.signatures.required': false,
    'extensions.startupScanScopes': 15,

    ...extraPrefs,
  };

  const lines = ['// generated by e2e/desktop/lib/profile.mjs', ...Object.entries(prefs).map(([k, v]) => prefLine(k, v))];
  writeFileSync(path.join(profileDir, 'user.js'), `${lines.join('\n')}\n`);
  return { profileDir, prefs };
}
